const I18nContext = createContext(null);
const KEY = 'farmiq.lang';

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const saved = typeof localStorage !== 'undefined' ? localStorage.getItem(KEY) : null;
    if (saved && dict[saved]) return saved;
    if (typeof navigator !== 'undefined') {
      const nav = String(navigator.language || 'en').toLowerCase();
      if (nav.startsWith('te')) return 'te';
      if (nav.startsWith('hi')) return 'hi';
    }
    return 'en';
  });

  useEffect(() => {
    try {
      localStorage.setItem(KEY, lang);
      document.documentElement.lang = lang;
    } catch {}
  }, [lang]);

  const t = useCallback(
    (key, fallback) => dict[lang]?.[key] ?? dict.en[key] ?? fallback ?? key,
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t, languages: LANGUAGES }), [lang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside <I18nProvider>');
  return ctx;
}
